// Writes js/pres-names.js: the names of the application's top-level data values, which the presentation
// environment (js/presentation.js) keeps in the browser between visits.
//
// The presentation reads these names from the app's own scripts at run time. A browser that opens the app
// straight from a file:/// link may not let a page read its own files, and then nothing would be kept, so the
// same list is also shipped in js/pres-names.js. Run this after adding or renaming a top-level variable:
//   node tools/gen-pres-names.js
// It parses exactly as presCandidates() does, over the scripts index.html loads, in the same order.
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const pres = fs.readFileSync(path.join(root, 'js', 'presentation.js'), 'utf8');
const skipSrc = /const PRES_SKIP=(\/.*\/);\r?\n/.exec(pres);
if (!skipSrc) throw new Error('PRES_SKIP not found in js/presentation.js');
const PRES_SKIP = eval(skipSrc[1]);
const srcs = [];
const re = /<script[^>]*\ssrc="(js\/[^"?]+)(?:\?[^"]*)?"/g;
let m;
while ((m = re.exec(html))) if (m[1] !== 'js/pres-names.js') srcs.push(m[1]);
const out = [];
srcs.forEach(function (src) {
  let text = '';
  try { text = fs.readFileSync(path.join(root, src), 'utf8'); } catch (e) { return; }
  let cont = false;
  text.split('\n').forEach(function (line) {
    const decl = /^(const|let|var)\s/.test(line);
    if (!decl && !cont) return;
    const r = decl ? /(?:^(?:const|let|var)\s+|,\s*)([a-z_$][\w$]*)\s*=(?!=)/g : /(?:^\s*|,\s*)([a-z_$][\w$]*)\s*=(?!=)/g;
    let x;
    while ((x = r.exec(line))) if (out.indexOf(x[1]) < 0 && !PRES_SKIP.test(x[1]) && (decl || !/Query$/.test(x[1]))) out.push(x[1]);
    const code = line.replace(/\/\/.*$/, '').trim(), bal = (code.match(/[\[{(]/g) || []).length - (code.match(/[\]})]/g) || []).length;
    cont = bal === 0 && /,$/.test(code);
  });
});
const body = '/* Generated by tools/gen-pres-names.js from the scripts index.html loads - do not edit by hand.\n'
  + '   The names of the application\'s top-level data values that the presentation environment keeps in the browser\n'
  + '   (js/presentation.js, presCandidates). Used when the browser does not let the page read its own script files,\n'
  + '   as happens when the app is opened straight from a file:/// link. ' + out.length + ' names from ' + srcs.length + ' scripts. */\n'
  + 'const PRES_NAMES_BUILT=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(root, 'js', 'pres-names.js'), body, 'utf8');
console.log('js/pres-names.js: ' + out.length + ' names from ' + srcs.length + ' scripts');
